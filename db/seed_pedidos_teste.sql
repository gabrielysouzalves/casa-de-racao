SELECT COUNT(*) AS pedidos_de_teste
FROM pedidos
WHERE pedido_cod LIKE '11111111-1111-4111-8111-%';

SELECT tipo, status, COUNT(*) AS quantidade
FROM pedidos
WHERE pedido_cod LIKE '11111111-1111-4111-8111-%'
GROUP BY tipo, status
ORDER BY tipo, status;

WITH duracoes AS (
  SELECT tipo, status,
    TIMESTAMPDIFF(MICROSECOND, criado_em, iniciado_em) / 60000000.0 AS espera_min,
    TIMESTAMPDIFF(MICROSECOND, iniciado_em, concluido_em) / 60000000.0 AS atendimento_min
  FROM pedidos
  WHERE pedido_cod LIKE '11111111-1111-4111-8111-%'
)
SELECT
  COUNT(*) AS pedidos,
  COUNT(espera_min) AS n_espera,
  ROUND(AVG(espera_min), 4) AS media_espera,
  ROUND(VAR_POP(espera_min), 4) AS variancia_espera,
  ROUND(STDDEV_POP(espera_min), 4) AS desvio_espera,
  COUNT(atendimento_min) AS n_atendimento,
  ROUND(AVG(atendimento_min), 4) AS media_atendimento,
  ROUND(VAR_POP(atendimento_min), 4) AS variancia_atendimento,
  ROUND(STDDEV_POP(atendimento_min), 4) AS desvio_atendimento
FROM duracoes;

SELECT tipo, DATE(criado_em) AS dia, COUNT(*) AS pedidos
FROM pedidos
WHERE pedido_cod LIKE '11111111-1111-4111-8111-%'
GROUP BY tipo, DATE(criado_em)
ORDER BY dia, tipo;

